function isOrderStatus(value: string | null | undefined): value is OrderStatus {
  return [
    'pending',
    'confirmed',
    'waiting_for_payment',
    'in_production',
    'ready',
    'delivered',
    'cancelled',
  ].includes(value ?? '')
}

function mapOrderRowToSummary(order: OrderRow, customerName: string | null, sellerName: string | null): Order {
  const total = normalizeNumber(order.total)
  const deposit = normalizeNumber(order.paid_amount)
  const balance = order.balance == null ? Math.max(0, total - deposit) : normalizeNumber(order.balance)

  return {
    balance,
    created_at: order.created_at,
    customer_name: customerName,
    deposit,
    discount_amount: normalizeNumber(order.discount_amount),
    discount_code: order.discount_code ?? null,
    id: order.id,
    order_number: order.order_number,
    requested_date: order.requested_date,
    seller_name: sellerName,
    source: order.source ?? null,
    status: order.status,
    total,
  }
}

function mapOrderItem(row: OrderItemRow): AdminOrderItem {
  const unitPrice = normalizeNumber(row.unit_price)
  const quantity = row.quantity ?? 0
  const lineTotal = row.line_total ?? row.total ?? row.subtotal ?? unitPrice * quantity

  return {
    blouse_size: row.blouse_size ?? null,
    color_hex: row.color_hex ?? null,
    color_name: row.color_name ?? null,
    line_total: normalizeNumber(lineTotal),
    notes: row.notes ?? null,
    pants_size: row.pants_size ?? null,
    product_name: row.product_name_snapshot ?? row.product_name ?? 'Producto sin nombre',
    quantity,
    unit_price: unitPrice,
  }
}

function mapTimelineEntry(row: OrderTimelineRow): AdminOrderTimelineEntry | null {
  const nextStatus = row.status ?? row.new_status

  if (!isOrderStatus(nextStatus)) {
    return null
  }

  return {
    created_at: row.created_at ?? null,
    status: nextStatus,
  }
}

function mapOrderPayment(row: OrderPaymentRow, profilesMap: Map<string, ProfileLookupRow>): OrderPayment {
  const recordedById = row.recorded_by_profile_id ?? null

  return {
    amount: normalizeNumber(row.amount),
    created_at: row.created_at ?? null,
    id: row.id,
    notes: row.notes ?? null,
    paid_at: row.paid_at ?? row.created_at ?? null,
    payment_method: row.payment_method ?? null,
    recorded_by_name: recordedById ? profilesMap.get(recordedById)?.full_name ?? null : null,
    recorded_by_profile_id: recordedById,
  }
}

async function getCustomersMap(customerIds: string[]) {
  if (!customerIds.length) {
    return new Map<string, CustomerLookupRow>()
  }

  const { data: customers, error } = await supabase
    .from('customers')
    .select('id, full_name, phone, email, city, state, address')
    .in('id', customerIds)

  if (error) {
    throw new Error('No fue posible consultar los clientes de los pedidos.')
  }

  return new Map((customers ?? []).map((customer) => [customer.id, customer as CustomerLookupRow]))
}

async function getProfilesMap(profileIds: string[]) {
  if (!profileIds.length) {
    return new Map<string, ProfileLookupRow>()
  }

  const { data, error } = await supabase
    .from('profiles')
    .select('id, full_name')
    .in('id', profileIds)

  if (error) {
    throw new Error('No fue posible consultar los perfiles del equipo.')
  }

  return new Map((data ?? []).map((profile) => [profile.id, profile as ProfileLookupRow]))
}

export async function getAdminOrders(scope?: AdminOrderScope): Promise<Order[]> {
  const baseSelect = 'id, order_number, status, subtotal, total, discount_amount, discount_code, paid_amount, balance, created_at, requested_date, customer_id, seller_profile_id, source'
  const legacySelect = 'id, order_number, status, subtotal, total, discount_amount, discount_code, paid_amount, balance, created_at, requested_date, customer_id, seller_profile_id'

  let query = supabase
    .from('orders')
    .select(baseSelect)

  if (scope?.sellerProfileId) {
    query = query.eq('seller_profile_id', scope.sellerProfileId)
  }

  let data: OrderRow[] | null = null
  let error: { message: string } | null = null

  const primaryResult = await query.order('created_at', { ascending: false })
  data = (primaryResult.data ?? null) as OrderRow[] | null
  error = primaryResult.error ? { message: primaryResult.error.message } : null

  if (error?.message.toLowerCase().includes('source')) {
    let legacyQuery = supabase
      .from('orders')
      .select(legacySelect)

    if (scope?.sellerProfileId) {
      legacyQuery = legacyQuery.eq('seller_profile_id', scope.sellerProfileId)
    }

    const legacyResult = await legacyQuery.order('created_at', { ascending: false })
    data = ((legacyResult.data ?? []) as OrderRow[]).map((order) => ({
      ...order,
      source: null,
    }))
    error = legacyResult.error ? { message: legacyResult.error.message } : null
  }

  if (error) {
    throw new Error(translateOrdersError(error.message))
  }

  const orders = (data ?? []).map((order) => ({
    ...order,
    source: order.source ?? null,
  }))

  if (!orders.length) {
    return []
  }

  const customerIds = orders
    .map((order) => order.customer_id)
    .filter((customerId): customerId is string => Boolean(customerId))
  const sellerIds = orders
    .map((order) => order.seller_profile_id)
    .filter((profileId): profileId is string => Boolean(profileId))

  const [customersMap, profilesMap] = await Promise.all([
    getCustomersMap(customerIds),
    getProfilesMap(sellerIds),
  ])

  return orders.map((order) =>
    mapOrderRowToSummary(
      order,
      order.customer_id ? customersMap.get(order.customer_id)?.full_name ?? null : null,
      order.seller_profile_id ? profilesMap.get(order.seller_profile_id)?.full_name ?? null : null,
    ),
  )
}

