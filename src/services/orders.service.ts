async function applyManualDiscountToOrder(params: {
  initialPaymentAmount: number
  manualDiscountAmount: number
  orderId: string
  subtotal: number
  existingDiscountAmount: number
}) {
  const nextDiscountAmount = params.existingDiscountAmount + params.manualDiscountAmount
  const nextTotal = Math.max(0, params.subtotal - nextDiscountAmount)
  const nextBalance = Math.max(0, nextTotal - params.initialPaymentAmount)

  const { error } = await supabase
    .from('orders')
    .update({
      balance: nextBalance,
      discount_amount: nextDiscountAmount,
      total: nextTotal,
    })
    .eq('id', params.orderId)

  if (error) {
    throw new Error(translateOrdersError(error.message))
  }

  return {
    discount_amount: nextDiscountAmount,
    total: nextTotal,
  }
}
